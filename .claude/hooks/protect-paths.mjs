// PreToolUse (Edit|Write|MultiEdit): block hand edits to generated or sensitive
// files. Exit 2 = refuse and tell Claude why.
import { readFileSync } from 'node:fs'

let input = {}
try {
  input = JSON.parse(readFileSync(0, 'utf8') || '{}')
} catch {
  process.exit(0)
}
const file = String(input.tool_input?.file_path ?? '').replace(/\\/g, '/')
if (!file) process.exit(0)

const rules = [
  [/(?:^|\/)app\/prisma\//, 'app/prisma/ is generated by `pnpm prisma generate`; change the schema and regenerate instead.'],
  [/(?:^|\/)\.env(?:\.(?!example$)[^/]*)?$/, '.env files hold secrets; ask the owner to edit them. (.env.example is allowed.)'],
  [/(?:^|\/)pnpm-lock\.yaml$/, 'pnpm-lock.yaml is generated by pnpm; run pnpm, never hand-edit it.'],
  [/(?:^|\/)node_modules\//, 'node_modules is installed state; do not edit it.'],
]
for (const [re, why] of rules) {
  if (re.test(file)) {
    console.error(`BLOCKED edit to ${file}: ${why}`)
    process.exit(2)
  }
}
